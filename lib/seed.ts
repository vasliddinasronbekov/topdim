function item(
  partial: Omit<Item, "id" | "status" | "createdAt"> & { id?: string; createdAt?: string; status?: Item["status"] },
): Item {
  return {
    id: partial.id ?? uid("it"),
    status: partial.status ?? "open",
    createdAt: partial.createdAt ?? partial.occurredAt,
    ...partial,
  };
}

